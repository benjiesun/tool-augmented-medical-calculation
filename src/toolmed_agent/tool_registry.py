import ast
import importlib.util
import json
import re
import types
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .utils import append_jsonl, ensure_dir, now_str, safe_str


@dataclass
class ToolExecResult:
    calculator_id: str
    tool_name: str
    result: Any
    error: str


def _norm_cid(v: Any) -> str:
    s = safe_str(v).strip()
    try:
        return str(int(float(s)))
    except Exception:
        return s


def _safe_code_check(code: str) -> Tuple[bool, str]:
    s = safe_str(code)
    if not s:
        return False, "empty_code"
    if "def calc(" not in s:
        return False, "missing_calc"
    forbidden = [
        r"(?i)\bimport\b",
        r"(?i)\bexec\s*\(",
        r"(?i)\beval\s*\(",
        r"(?i)\bopen\s*\(",
        r"(?i)\bos\.",
        r"(?i)\bsys\.",
        r"(?i)\bsubprocess\b",
        r"__",
    ]
    for pat in forbidden:
        if re.search(pat, s):
            return False, f"forbidden:{pat}"

    try:
        ast.parse(s)
    except Exception as e:
        return False, f"syntax_error:{type(e).__name__}:{e}"
    return True, ""


class CalculationToolRegistry:
    def __init__(self, calc_tools_dir: str):
        self.root = Path(calc_tools_dir).resolve()
        ensure_dir(str(self.root))
        candidate_generated_dir = self.root / "generated_tools"
        if candidate_generated_dir.exists():
            self.generated_dir = candidate_generated_dir
        elif list(self.root.glob("calculator_*.py")):
            self.generated_dir = self.root
        else:
            self.generated_dir = candidate_generated_dir
        ensure_dir(str(self.generated_dir))
        self.registry_path = self.root / "tool_registry.jsonl"
        self.registry_path.touch(exist_ok=True)
        self._module_cache: Dict[str, Any] = {}

    def _tool_path(self, calculator_id: Any) -> Path:
        cid = _norm_cid(calculator_id)
        return self.generated_dir / f"calculator_{cid}.py"

    def _tool_candidates(self, calculator_id: Any) -> List[Path]:
        cid = _norm_cid(calculator_id)
        exact = self.generated_dir / f"calculator_{cid}.py"
        if exact.exists():
            return [exact]
        cands = sorted(self.generated_dir.glob(f"calculator_{cid}_*.py"))
        return cands

    def has_tool(self, calculator_id: Any) -> bool:
        return bool(self._tool_candidates(calculator_id))

    def register_tool(
        self,
        calculator_id: Any,
        calculator_name: str,
        required_entities: List[str],
        tool_code: str,
        source: str,
    ) -> Dict[str, Any]:
        cid = _norm_cid(calculator_id)
        path = self._tool_path(cid)

        ok, reason = _safe_code_check(tool_code)
        final_code = safe_str(tool_code)
        if not ok:
            final_code = (
                "def calc(relevant):\n"
                "    return 'N/A'\n"
            )

        header = (
            "# Auto-generated by medagent\n"
            f"# time: {now_str()}\n"
            f"# calculator_id: {cid}\n"
            f"# calculator_name: {safe_str(calculator_name)}\n"
            f"# required_entities: {required_entities}\n"
            f"# source: {safe_str(source)}\n\n"
        )
        path.write_text(header + final_code.strip() + "\n", encoding="utf-8")

        row = {
            "time": now_str(),
            "calculator_id": cid,
            "calculator_name": safe_str(calculator_name),
            "required_entities": required_entities,
            "tool_path": str(path),
            "source": safe_str(source),
            "valid": bool(ok),
            "validation_message": "" if ok else reason,
        }
        append_jsonl(str(self.registry_path), [row])
        self._module_cache.pop(str(path), None)
        return row

    def _load_module(self, path: Path):
        key = str(path)
        if key in self._module_cache:
            return self._module_cache[key]

        first_error: Optional[Exception] = None
        try:
            spec = importlib.util.spec_from_file_location(path.stem, path)
            if spec is not None and spec.loader is not None:
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                self._module_cache[key] = module
                return module
            first_error = RuntimeError(f"failed to load spec from {path}")
        except Exception as e:
            first_error = e

        raw = path.read_text(encoding="utf-8")
        for source in self._candidate_tool_sources(raw):
            fixed = self._trim_valid_tool_source(source)
            if not fixed:
                continue
            try:
                module = types.ModuleType(f"{path.stem}_recovered")
                module.__file__ = str(path)
                exec(compile(fixed, str(path), "exec"), module.__dict__)
                self._module_cache[key] = module
                return module
            except Exception as e:
                first_error = e

        raise RuntimeError(f"failed_to_load_tool_module:{path}:{first_error}")

    @staticmethod
    def _source_has_calc(source: str) -> bool:
        try:
            tree = ast.parse(source)
        except Exception:
            return False
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name == "calc":
                return True
        return False

    @classmethod
    def _trim_valid_tool_source(cls, source: str) -> str:
        text = safe_str(source).replace("\r\n", "\n").replace("\r", "\n")
        if "def calc" not in text:
            return ""
        text = text[text.find("def calc") :]
        lines: List[str] = []
        for raw_line in text.split("\n"):
            stripped = safe_str(raw_line).strip()
            if stripped.startswith("```"):
                continue
            # Some broken tool files are dumped as escaped JSON snippets and may
            # leave a dangling object-closer line after decoded code.
            if stripped == "}":
                continue
            line = raw_line
            # Fix dangling trailing quote, e.g. `return x"` from malformed dumps.
            if line.count('"') % 2 == 1 and line.rstrip().endswith('"'):
                line = line.rstrip()[:-1]
            lines.append(line)
        for end in range(len(lines), 0, -1):
            cand = "\n".join(lines[:end]).rstrip()
            if not cand:
                continue
            cand += "\n"
            if cls._source_has_calc(cand):
                return cand
        return ""

    @staticmethod
    def _candidate_tool_sources(raw: str) -> List[str]:
        out: List[str] = []
        text = safe_str(raw)
        if text:
            out.append(text)
        if text.lstrip().startswith("{") and "tool_code" in text:
            try:
                obj = json.loads(text)
                code = safe_str(obj.get("tool_code", ""))
                if code:
                    out.append(code)
            except Exception:
                pass
        if "\\n" in text:
            decoded = text.replace("\\r\\n", "\n").replace("\\n", "\n").replace("\\t", "\t")
            decoded = decoded.replace('\\"', '"').replace("\\'", "'")
            if decoded and decoded not in out:
                out.append(decoded)
        return out

    def calculate(self, calculator_id: Any, relevant: Dict[str, Any]) -> ToolExecResult:
        cid = _norm_cid(calculator_id)
        cands = self._tool_candidates(cid)
        path = cands[0] if cands else self._tool_path(cid)
        tool_name = path.stem
        if not path.exists():
            return ToolExecResult(
                calculator_id=cid,
                tool_name=tool_name,
                result="",
                error=f"tool_not_found:{path}",
            )

        try:
            mod = self._load_module(path)
            fn = getattr(mod, "calc", None)
            if not callable(fn):
                return ToolExecResult(
                    calculator_id=cid,
                    tool_name=tool_name,
                    result="",
                    error="tool_missing_calc",
                )
            val = fn(relevant or {})
            return ToolExecResult(calculator_id=cid, tool_name=tool_name, result=val, error="")
        except Exception as e:
            return ToolExecResult(
                calculator_id=cid,
                tool_name=tool_name,
                result="",
                error=f"tool_runtime_error:{type(e).__name__}:{e}",
            )

    def list_tools(self) -> List[str]:
        out = []
        for p in sorted(self.generated_dir.glob("calculator_*.py")):
            out.append(p.stem)
        return out

    def infer_required_entities_from_tool(self, calculator_id: Any) -> List[str]:
        cands = self._tool_candidates(calculator_id)
        path = cands[0] if cands else self._tool_path(calculator_id)
        if not path.exists():
            return []
        try:
            for line in path.read_text(encoding="utf-8").splitlines()[:80]:
                s = safe_str(line).strip()
                if not s.startswith("#"):
                    continue
                if not s.lower().startswith("# required_entities:"):
                    continue
                raw = s.split(":", 1)[1].strip()
                obj = ast.literal_eval(raw)
                if isinstance(obj, list):
                    return [safe_str(x).strip() for x in obj if safe_str(x).strip()]
        except Exception:
            return []
        return []

    def latest_required_entities(self, calculator_id: Any) -> List[str]:
        cid = _norm_cid(calculator_id)
        rows = []
        with self.registry_path.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                except Exception:
                    continue
                if _norm_cid(obj.get("calculator_id", "")) == cid:
                    rows.append(obj)
        if not rows:
            return self.infer_required_entities_from_tool(cid)
        latest = rows[-1]
        req = latest.get("required_entities", [])
        out = [safe_str(x).strip() for x in req if safe_str(x).strip()]
        if out:
            return out
        return self.infer_required_entities_from_tool(cid)
